<h2>Perché un conto o una carta dedicati</h2>
<p>Se vendi, conviene avere un posto <strong>solo per i soldi delle vendite</strong>. Così vedi subito quanto hai incassato, non mescoli le spese personali e la contabilità (e le tasse) sono più semplici.</p>

<h2>Le possibilità</h2>
<table>
    <tr><th>Soluzione</th><th>Com'è fatta</th><th>Adatta per</th></tr>
    <tr><td><strong>Conto corrente</strong> della tua banca</td><td>Hai già un IBAN; di solito ha canone e costi per i bonifici.</td><td>Chi ha già un conto e vende poco.</td></tr>
    <tr><td><strong>Carta prepagata con IBAN</strong></td><td>Una carta ricaricabile con IBAN italiano: puoi ricevere bonifici e usarla per le spese.</td><td>Privati e piccole vendite.</td></tr>
    <tr><td><strong>Conto online</strong></td><td>Si apre dal telefono in pochi minuti, con IBAN e carta; ci sono opzioni dedicate alle attività.</td><td>Chi vuole costi bassi e gestione da app.</td></tr>
</table>

<h2>Cosa controllare prima di scegliere</h2>
<ul>
    <li>Che l'<strong>IBAN sia italiano</strong> (inizia con IT): alcuni servizi accettano solo IBAN del tuo paese per gli accrediti.</li>
    <li>Che sia <strong>intestato a te</strong> (o alla tua attività): non usare conti di altre persone.</li>
    <li>Canone, costo di bonifici e prelievi, <strong>limiti di importo</strong> e se accetta <strong>bonifici istantanei</strong>.</li>
    <li>Che l'azienda sia <strong>regolata</strong> (banca o istituto di pagamento autorizzato): lo trovi indicato nel sito ufficiale.</li>
    <li>Se sei un'attività con partita IVA, verifica che il conto sia utilizzabile per uso <strong>professionale</strong>.</li>
</ul>

<h2>Come si apre (in generale)</h2>
<ol>
    <li>Scarica l'app <strong>ufficiale</strong> dall'App Store o da Google Play (controlla il nome dell'azienda).</li>
    <li>Registrati con numero di telefono e email e verifica l'identità (documento e video-selfie).</li>
    <li>Attendi l'approvazione e copia il tuo <strong>IBAN</strong> dall'app.</li>
    <li>Usa quell'IBAN quando Stripe, PayPal o i tuoi clienti ti chiedono dove accreditare i soldi.</li>
</ol>

