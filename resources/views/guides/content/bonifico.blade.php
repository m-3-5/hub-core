<h2>Come funziona</h2>
<p>Il cliente ti paga con un bonifico sul tuo <strong>IBAN</strong>. È semplice e non ha commissioni da parte di terzi, ma devi controllare tu che i soldi siano arrivati prima di consegnare.</p>

<h2>Cosa serve</h2>
<ul>
    <li>Un conto con <strong>IBAN italiano</strong> intestato a te o alla tua attività (conto corrente, carta con IBAN o conto online: vedi la guida su <a href="{{ route('guides.show', 'carte-e-conti-online') }}">carte e conti online</a>).</li>
    <li>I dati da comunicare al cliente: <strong>intestatario, IBAN, importo e causale</strong>.</li>
</ul>

<h2>Come farti pagare in modo ordinato</h2>
<ol>
    <li>Scrivi al cliente i dati completi: intestatario, IBAN, importo esatto e una <strong>causale chiara</strong> (es. «Ordine 123 – Mario Rossi»).</li>
    <li>Chiedi la <strong>ricevuta del bonifico</strong> (CRO/TRN) per riconoscerlo più in fretta.</li>
    <li>Prima di consegnare controlla che i soldi siano davvero sul conto: un bonifico «ordinario» può impiegare 1-2 giorni lavorativi; il <strong>bonifico istantaneo</strong> arriva in pochi secondi.</li>
    <li>Segna il pagamento ricevuto e, se serve, emetti ricevuta o fattura.</li>
</ol>

<h2>Suggerimenti utili</h2>
<ul>
    <li>Per importi alti o clienti nuovi, aspetta l'accredito vero e non fidarti di una semplice schermata.</li>
    <li>Non accettare «assegni» o bonifici con importi in più «da restituire»: è una truffa molto comune.</li>
    <li>Tieni separati i soldi delle vendite da quelli personali (vedi <a href="{{ route('guides.show', 'carte-e-conti-online') }}">conti dedicati</a>): ti semplifica la contabilità.</li>
    <li>Il bonifico non ha protezione automatica per il cliente: se vuoi che si fidi di più, usa i <a href="{{ route('guides.show', 'pagamenti-protetti') }}">pagamenti protetti</a>.</li>
</ul>

