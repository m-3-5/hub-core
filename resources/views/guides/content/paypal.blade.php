<h2>Cos'è</h2>
<p>PayPal permette di ricevere pagamenti con il conto PayPal, la carta o la carta collegata del cliente. È molto conosciuto: molti clienti si fidano a pagare così.</p>

<h2>Come aprire un conto PayPal per vendere</h2>
<ol>
    <li>Vai sul sito ufficiale <a href="https://www.paypal.com/it/business" target="_blank" rel="noopener">paypal.com/it/business</a> e scegli di aprire un <strong>conto Business</strong> (consigliato se vendi con regolarità; il conto Personale ha più limiti per le vendite).</li>
    <li>Registrati con email e password, poi inserisci i dati dell'attività o i tuoi dati personali.</li>
    <li>Collega un <strong>conto bancario o una carta</strong> per poter trasferire i soldi ricevuti.</li>
    <li>Verifica l'identità e l'email: senza verifica i prelievi possono essere limitati.</li>
    <li>Attiva la <strong>verifica in due passaggi</strong>.</li>
</ol>

<h2>Come farti pagare con un link</h2>
<ol>
    <li>Crea il tuo link personale <strong>PayPal.me</strong> da <a href="https://www.paypal.com/paypalme/" target="_blank" rel="noopener">paypal.com/paypalme</a>: è un indirizzo del tipo <code>paypal.me/tuonome</code>.</li>
    <li>Puoi aggiungere l'importo alla fine del link (es. <code>paypal.me/tuonome/25</code>) per far pagare esattamente quella cifra.</li>
    <li>Invia il link al cliente o mettilo nella descrizione del prodotto.</li>
</ol>

<h2>Suggerimenti utili</h2>
<ul>
    <li>Chiedi al cliente di pagare con <strong>«Beni e servizi»</strong> e non «Amici e familiari»: è l'opzione che dà protezione a lui e a te per le vendite.</li>
    <li>Controlla la tabella delle commissioni PayPal sul <a href="https://www.paypal.com/it/business/paypal-business-fees" target="_blank" rel="noopener">sito ufficiale</a>: cambiano per tipo di pagamento e paese.</li>
    <li>PayPal può <strong>trattenere</strong> i fondi di un nuovo conto o in caso di contestazione: non contare sui soldi finché non sono disponibili.</li>
    <li>Conserva sempre prova di consegna o di prestazione: ti serve se il cliente apre una contestazione.</li>
</ul>

